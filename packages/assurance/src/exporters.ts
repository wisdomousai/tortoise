import { parseCidr } from '@agent-native/egress';
import type { RuleSet } from './rules';

export const exportFormats = [
  'json',
  'nftables',
  'windows-firewall',
  'k8s-networkpolicy',
  'k8s-pod',
  'compose',
  'systemd',
] as const;
export type ExportFormat = (typeof exportFormats)[number];

/** Deployment facts the rule set does not know. Defaults suit a Linux service install. */
export interface ExportOptions {
  /** OS account the service runs as; nftables matches it, systemd and containers run as it. */
  readonly user?: string;
  readonly uid?: number;
  /** Service executable, for program-scoped Windows rules and the systemd unit. */
  readonly executable?: string;
  readonly workspace?: string;
  readonly auditLog?: string;
  /** Site policy path the service is started with. */
  readonly sitePolicy?: string;
  /** Container image for the Kubernetes and compose manifests. */
  readonly image?: string;
}

const slug = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const identifier = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, '_');
const familyOf = (address: string) => parseCidr(address).family;

function defaults(rules: RuleSet, options: ExportOptions) {
  const name = slug(rules.application);
  return {
    name,
    user: options.user ?? name,
    uid: options.uid ?? 10001,
    executable: options.executable ?? `/opt/${name}/service`,
    workspace: options.workspace ?? `/var/lib/${name}/workspace`,
    auditLog: options.auditLog ?? `/var/lib/${name}/audit`,
    sitePolicy: options.sitePolicy ?? `/etc/${name}/site-policy.json`,
    image: options.image ?? `${name}:latest`,
  };
}

const header = (rules: RuleSet, format: ExportFormat, comment: string) =>
  [
    `${comment} Generated by \`${rules.application} security export --format ${format}\`. Do not edit; regenerate.`,
    `${comment} Policy ${rules.policyDigest.slice(0, 16)} (${rules.profile}, ${rules.mode}). Default: deny all egress except loopback and the rules below.`,
    ...rules.unresolved.map(
      (gap) =>
        `${comment} NOT ENFORCED: ${gap.destination} (${gap.host}) ${gap.reason === 'HOSTNAME_ONLY' ? 'has no addresses in the site policy' : 'has no port'}; it stays blocked here.`,
    ),
    ...(rules.dns.needed && !rules.dns.resolvers.length
      ? [
          `${comment} DNS: bound URLs use host names but no resolvers were given (--resolver); name lookups will be blocked.`,
        ]
      : []),
  ].join('\n');

function nftables(rules: RuleSet, options: ExportOptions): string {
  const d = defaults(rules, options);
  const match = (address: string) => (familyOf(address) === 4 ? 'ip daddr' : 'ip6 daddr');
  const lines = [
    '#!/usr/sbin/nft -f',
    header(rules, 'nftables', '#'),
    `# Applies to sockets owned by user "${d.user}"; other users are unaffected.`,
    `table inet ${identifier(rules.application)} {`,
    '  chain output {',
    '    type filter hook output priority filter; policy accept;',
    `    meta skuid != "${d.user}" accept`,
    '    oif "lo" accept',
    '    ct state established,related accept',
  ];
  for (const resolver of rules.dns.resolvers)
    for (const transport of ['udp', 'tcp'])
      lines.push(`    ${match(resolver)} ${resolver} ${transport} dport 53 accept comment "dns"`);
  for (const rule of rules.allow) {
    lines.push(`    # ${rule.destination} (${rule.owner}, ${rule.scope}): ${rule.purpose}`);
    for (const address of rule.addresses)
      lines.push(
        `    ${match(address)} ${address} ${rule.transport} dport ${rule.port} accept comment "${rule.destination}"`,
      );
  }
  lines.push(
    `    counter log prefix "${d.name}-egress-deny " drop`,
    '  }',
    '}',
    ...(rules.ingress.listen === 'loopback'
      ? ['# Ingress: the authority listens on loopback only; no inbound rule is needed.']
      : [
          `# Ingress: ${rules.ingress.listen} listener on port ${rules.ingress.port ?? 'unset'}; open it in your host input policy to the clients that hold certificates.`,
        ]),
    '',
  );
  return lines.join('\n');
}

// Windows evaluates block rules before allow rules, so "deny all but X" for one program is a
// block rule over the complement of X. Ranges are computed per address family.
const widths = { 4: 32n, 6: 128n } as const;
function formatAddress(value: bigint, family: 4 | 6): string {
  if (family === 4)
    return [24n, 16n, 8n, 0n].map((shift) => String((value >> shift) & 0xffn)).join('.');
  const groups: string[] = [];
  for (let shift = 112n; shift >= 0n; shift -= 16n)
    groups.push(((value >> shift) & 0xffffn).toString(16));
  return groups.join(':');
}
function complement(networks: readonly string[], family: 4 | 6): string[] {
  const width = widths[family];
  const ranges = networks
    .map(parseCidr)
    .filter((cidr) => cidr.family === family)
    .map((cidr) => {
      const size = 1n << (width - BigInt(cidr.bits));
      return [cidr.base, cidr.base + size - 1n] as const;
    })
    .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const result: string[] = [];
  let next = 0n;
  const max = (1n << width) - 1n;
  for (const [start, end] of ranges) {
    if (start > next)
      result.push(`${formatAddress(next, family)}-${formatAddress(start - 1n, family)}`);
    if (end + 1n > next) next = end + 1n;
  }
  if (next <= max) result.push(`${formatAddress(next, family)}-${formatAddress(max, family)}`);
  return result;
}
function portComplement(ports: readonly number[]): string[] {
  const result: string[] = [];
  let next = 1;
  for (const port of [...new Set(ports)].sort((a, b) => a - b)) {
    if (port > next) result.push(port - 1 === next ? `${next}` : `${next}-${port - 1}`);
    next = port + 1;
  }
  if (next <= 65535) result.push(next === 65535 ? '65535' : `${next}-65535`);
  return result;
}
const psList = (values: readonly string[]) =>
  `@(${values.map((value) => `'${value}'`).join(', ')})`;

function windowsFirewall(rules: RuleSet, options: ExportOptions): string {
  const d = defaults(rules, options);
  const executable = options.executable ?? `C:\\Program Files\\${rules.application}\\service.exe`;
  const loopback = ['127.0.0.0/8', '::1/128'];
  const allowed = [
    ...new Set([...rules.allow.flatMap((rule) => rule.addresses), ...rules.dns.resolvers]),
  ];
  const lines = [
    header(rules, 'windows-firewall', '#'),
    '# Run in an elevated PowerShell. Every rule is scoped to the service executable.',
    "$ErrorActionPreference = 'Stop'",
    `$Program = '${executable.replace(/'/g, "''")}'`,
    `$Group = '${rules.application} egress (generated)'`,
    'Get-NetFirewallRule -Group $Group -ErrorAction SilentlyContinue | Remove-NetFirewallRule',
    '# Block every destination that no rule allows (loopback is never filtered by Windows Firewall).',
  ];
  for (const family of [4, 6] as const) {
    const ranges = complement([...loopback, ...allowed], family);
    if (ranges.length)
      lines.push(
        `New-NetFirewallRule -Group $Group -DisplayName '${d.name}: block other IPv${family}' -Direction Outbound -Action Block -Program $Program -Profile Any -RemoteAddress ${psList(ranges)} | Out-Null`,
      );
  }
  // On allowed addresses, block the protocols and ports no rule names.
  const byAddress = new Map<string, { tcp: number[]; udp: number[] }>();
  const add = (address: string, transport: 'tcp' | 'udp', port: number) => {
    const entry = byAddress.get(address) ?? { tcp: [], udp: [] };
    entry[transport].push(port);
    byAddress.set(address, entry);
  };
  for (const rule of rules.allow)
    for (const address of rule.addresses) add(address, rule.transport, rule.port);
  for (const resolver of rules.dns.resolvers) {
    add(resolver, 'udp', 53);
    add(resolver, 'tcp', 53);
  }
  for (const [address, ports] of [...byAddress].sort(([a], [b]) => (a < b ? -1 : 1)))
    for (const transport of ['tcp', 'udp'] as const) {
      const blocked = portComplement(ports[transport]);
      if (blocked.length)
        lines.push(
          `New-NetFirewallRule -Group $Group -DisplayName '${d.name}: block other ${transport.toUpperCase()} ports to ${address}' -Direction Outbound -Action Block -Program $Program -Profile Any -RemoteAddress '${address}' -Protocol ${transport.toUpperCase()} -RemotePort ${psList(blocked)} | Out-Null`,
        );
    }
  for (const rule of rules.allow)
    lines.push(
      `New-NetFirewallRule -Group $Group -DisplayName '${d.name}: ${rule.destination}' -Description '${rule.purpose.replace(/'/g, "''")}' -Direction Outbound -Action Allow -Program $Program -Profile Any -RemoteAddress ${psList(rule.addresses)} -Protocol ${rule.transport.toUpperCase()} -RemotePort ${rule.port} | Out-Null`,
    );
  lines.push(
    '# Protocols other than TCP and UDP to allowed addresses are not blocked by these rules.',
    '',
  );
  return lines.join('\n');
}

/** Minimal YAML for plain JSON data; strings are double-quoted JSON, which YAML accepts. */
function yaml(value: unknown, indent = ''): string {
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return value
      .map((item) => {
        const text = yaml(item, `${indent}  `);
        return `\n${indent}- ${text.replace(/^\n\s*/, '')}`;
      })
      .join('');
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).filter(([, item]) => item !== undefined);
    if (!entries.length) return '{}';
    return entries
      .map(([key, item]) => {
        const text = yaml(item, `${indent}  `);
        const scalar = !text.startsWith('\n');
        return `\n${indent}${/^[A-Za-z0-9_.\/-]+$/.test(key) ? key : JSON.stringify(key)}:${scalar ? ' ' : ''}${text}`;
      })
      .join('');
  }
  return typeof value === 'string' ? JSON.stringify(value) : String(value);
}
const document = (rules: RuleSet, format: ExportFormat, value: unknown, notes: string[] = []) =>
  `${[header(rules, format, '#'), ...notes.map((note) => `# ${note}`)].join('\n')}\n${yaml(value).replace(/^\n/, '')}\n`;

function networkPolicy(rules: RuleSet, options: ExportOptions): string {
  const d = defaults(rules, options);
  const cidr = (address: string) =>
    address.includes('/') ? address : `${address}/${familyOf(address) === 4 ? 32 : 128}`;
  const dns = rules.dns.resolvers.length
    ? [
        {
          to: rules.dns.resolvers.map((resolver) => ({ ipBlock: { cidr: cidr(resolver) } })),
          ports: [
            { protocol: 'UDP', port: 53 },
            { protocol: 'TCP', port: 53 },
          ],
        },
      ]
    : rules.dns.needed
      ? [
          {
            to: [
              {
                namespaceSelector: {
                  matchLabels: { 'kubernetes.io/metadata.name': 'kube-system' },
                },
                podSelector: { matchLabels: { 'k8s-app': 'kube-dns' } },
              },
            ],
            ports: [
              { protocol: 'UDP', port: 53 },
              { protocol: 'TCP', port: 53 },
            ],
          },
        ]
      : [];
  return document(rules, 'k8s-networkpolicy', {
    apiVersion: 'networking.k8s.io/v1',
    kind: 'NetworkPolicy',
    metadata: { name: `${d.name}-egress`, labels: { 'app.kubernetes.io/name': d.name } },
    spec: {
      podSelector: { matchLabels: { 'app.kubernetes.io/name': d.name } },
      policyTypes: ['Ingress', 'Egress'],
      ingress:
        rules.ingress.listen === 'mtls' && rules.ingress.port
          ? [{ ports: [{ protocol: 'TCP', port: rules.ingress.port }] }]
          : [],
      egress: [
        ...dns,
        ...rules.allow.map((rule) => ({
          to: rule.addresses.map((address) => ({ ipBlock: { cidr: cidr(address) } })),
          ports: [{ protocol: rule.transport.toUpperCase(), port: rule.port }],
        })),
      ],
    },
  });
}

const serviceArgs = (d: ReturnType<typeof defaults>) => [
  'serve',
  '--workspace',
  d.workspace,
  '--audit-log',
  d.auditLog,
  '--site-policy',
  d.sitePolicy,
];

function pod(rules: RuleSet, options: ExportOptions): string {
  const d = defaults(rules, options);
  return document(rules, 'k8s-pod', {
    apiVersion: 'v1',
    kind: 'Pod',
    metadata: { name: d.name, labels: { 'app.kubernetes.io/name': d.name } },
    spec: {
      automountServiceAccountToken: false,
      securityContext: {
        runAsNonRoot: true,
        runAsUser: d.uid,
        runAsGroup: d.uid,
        fsGroup: d.uid,
        seccompProfile: { type: 'RuntimeDefault' },
      },
      containers: [
        {
          name: d.name,
          image: d.image,
          args: serviceArgs(d),
          securityContext: {
            allowPrivilegeEscalation: false,
            readOnlyRootFilesystem: true,
            privileged: false,
            capabilities: { drop: ['ALL'] },
          },
          volumeMounts: [
            { name: 'workspace', mountPath: d.workspace },
            { name: 'audit', mountPath: d.auditLog },
            {
              name: 'site-policy',
              mountPath: d.sitePolicy,
              subPath: 'site-policy.json',
              readOnly: true,
            },
            { name: 'tmp', mountPath: '/tmp' },
          ],
        },
      ],
      volumes: [
        { name: 'workspace', persistentVolumeClaim: { claimName: `${d.name}-workspace` } },
        { name: 'audit', persistentVolumeClaim: { claimName: `${d.name}-audit` } },
        { name: 'site-policy', configMap: { name: `${d.name}-site-policy` } },
        { name: 'tmp', emptyDir: { medium: 'Memory', sizeLimit: '64Mi' } },
      ],
    },
  });
}

function compose(rules: RuleSet, options: ExportOptions): string {
  const d = defaults(rules, options);
  return document(
    rules,
    'compose',
    {
      services: {
        [d.name]: {
          image: d.image,
          command: serviceArgs(d),
          user: `${d.uid}:${d.uid}`,
          read_only: true,
          cap_drop: ['ALL'],
          security_opt: ['no-new-privileges:true'],
          tmpfs: ['/tmp:size=64m'],
          volumes: [
            `${d.name}-workspace:${d.workspace}`,
            `${d.name}-audit:${d.auditLog}`,
            `./site-policy.json:${d.sitePolicy}:ro`,
          ],
          networks: [`${d.name}-egress`],
        },
      },
      networks: {
        [`${d.name}-egress`]: { driver: 'bridge' },
      },
      volumes: { [`${d.name}-workspace`]: {}, [`${d.name}-audit`]: {} },
    },
    [
      'NOT ENFORCED: Compose cannot filter egress by destination. Apply the nftables export on the',
      'host (or k8s-networkpolicy in a cluster); this file only hardens the container.',
    ],
  );
}

function systemd(rules: RuleSet, options: ExportOptions): string {
  const d = defaults(rules, options);
  const allow = [
    'localhost',
    ...new Set([...rules.dns.resolvers, ...rules.allow.flatMap((rule) => rule.addresses)]),
  ];
  return [
    header(rules, 'systemd', '#'),
    '# IPAddressAllow restricts addresses, not ports; pair it with the nftables export for ports.',
    '[Unit]',
    `Description=${rules.application} local authority`,
    'After=network-online.target',
    'Wants=network-online.target',
    '',
    '[Service]',
    'Type=simple',
    `User=${d.user}`,
    `Group=${d.user}`,
    `ExecStart=${[d.executable, ...serviceArgs(d)].join(' ')}`,
    'Restart=on-failure',
    'UMask=0077',
    'IPAddressDeny=any',
    ...allow.map((address) => `IPAddressAllow=${address}`),
    'NoNewPrivileges=yes',
    'ProtectSystem=strict',
    'ProtectHome=yes',
    'PrivateTmp=yes',
    '# Hides serial, HID and camera devices. For declared devices, remove it and add DeviceAllow=.',
    'PrivateDevices=yes',
    `ReadWritePaths=${d.workspace} ${d.auditLog}`,
    `ReadOnlyPaths=${d.sitePolicy}`,
    'CapabilityBoundingSet=',
    'AmbientCapabilities=',
    'RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6',
    'RestrictNamespaces=yes',
    'RestrictRealtime=yes',
    'RestrictSUIDSGID=yes',
    'LockPersonality=yes',
    'ProtectClock=yes',
    'ProtectHostname=yes',
    'ProtectKernelLogs=yes',
    'ProtectKernelModules=yes',
    'ProtectKernelTunables=yes',
    'ProtectControlGroups=yes',
    'ProtectProc=invisible',
    'ProcSubset=pid',
    'SystemCallArchitectures=native',
    'SystemCallFilter=@system-service',
    // @resources stays allowed: Bun raises its open-file limit at startup. A refused call
    // returns EPERM instead of killing the service, so a too-strict filter is visible in logs.
    'SystemCallFilter=~@privileged',
    'SystemCallErrorNumber=EPERM',
    '# MemoryDenyWriteExecute is not set: the JavaScript JIT needs writable executable memory.',
    '',
    '[Install]',
    'WantedBy=multi-user.target',
    '',
  ].join('\n');
}

/**
 * Render a rule set for one enforcement point. Every output is deterministic text, carries the
 * policy digest, and lists any bound destination it could not enforce by address. These are
 * exported artifacts: applying them is the operator's step, and nothing here touches the host.
 */
export function exportRules(
  rules: RuleSet,
  format: ExportFormat,
  options: ExportOptions = {},
): string {
  switch (format) {
    case 'json':
      return `${JSON.stringify(rules, null, 2)}\n`;
    case 'nftables':
      return nftables(rules, options);
    case 'windows-firewall':
      return windowsFirewall(rules, options);
    case 'k8s-networkpolicy':
      return networkPolicy(rules, options);
    case 'k8s-pod':
      return pod(rules, options);
    case 'compose':
      return compose(rules, options);
    case 'systemd':
      return systemd(rules, options);
  }
}
