// Expo config plugin, listed by `mobile:prepare` (through `nativeOsConfig`) when the application
// declares shortcut handlers, with `{ shortcuts: [{ id, title, link }] }`. On Android it writes
// static app shortcuts (`res/xml/os_shortcuts.xml`), each a VIEW intent to the main activity
// carrying the shortcut link, so the app receives it like any link. Titles go into string
// resources, because a shortcut label must be one.
const { mkdirSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withStringsXml,
} = require('expo/config-plugins');

const META = 'android.app.shortcuts';
const RESOURCE = '@xml/os_shortcuts';
const label = (index) => `os_shortcut_${index}`;

const xml = (text) =>
  String(text)
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

/** A title as an Android string resource reads it literally. */
const resourceText = (text) =>
  String(text)
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
    .replace(/^([@?])/, '\\$1');

function shortcutsXml(shortcuts, packageName, targetClass) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by @agent-native/mobile/shortcuts at prebuild. Do not edit. -->',
    '<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">',
    ...shortcuts.flatMap((shortcut, index) => [
      `  <shortcut android:shortcutId="${xml(shortcut.id)}" android:enabled="true" ` +
        `android:shortcutShortLabel="@string/${label(index)}">`,
      `    <intent android:action="android.intent.action.VIEW" ` +
        `android:targetPackage="${xml(packageName)}" android:targetClass="${xml(targetClass)}" ` +
        `android:data="${xml(shortcut.link)}" />`,
      '  </shortcut>',
    ]),
    '</shortcuts>',
    '',
  ].join('\n');
}

/** `manifest` with the main activity pointing at the shortcuts resource once. */
function setShortcutsMetaData(manifest) {
  const activity = AndroidConfig.Manifest.getMainActivityOrThrow(manifest);
  const kept = (activity['meta-data'] ?? []).filter((item) => item.$?.['android:name'] !== META);
  activity['meta-data'] = [...kept, { $: { 'android:name': META, 'android:resource': RESOURCE } }];
  return manifest;
}

module.exports = function withShortcuts(config, options = {}) {
  const shortcuts = options.shortcuts ?? [];
  if (!shortcuts.length) return config;
  const packageName = config.android?.package;
  if (!packageName) throw new Error('Shortcuts need android.package in the app configuration');
  config = withAndroidManifest(config, (config) => {
    config.modResults = setShortcutsMetaData(config.modResults);
    return config;
  });
  config = withStringsXml(config, (config) => {
    config.modResults = AndroidConfig.Strings.setStringItem(
      shortcuts.map((shortcut, index) => ({
        $: { name: label(index), translatable: 'false' },
        _: resourceText(shortcut.title),
      })),
      config.modResults,
    );
    return config;
  });
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const directory = join(config.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      mkdirSync(directory, { recursive: true });
      writeFileSync(
        join(directory, 'os_shortcuts.xml'),
        // An explicit intent names the activity; Expo's main activity is always MainActivity.
        shortcutsXml(shortcuts, packageName, `${packageName}.MainActivity`),
      );
      return config;
    },
  ]);
};

module.exports.shortcutsXml = shortcutsXml;
module.exports.setShortcutsMetaData = setShortcutsMetaData;
module.exports.resourceText = resourceText;
