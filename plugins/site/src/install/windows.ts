import type { InstallLayout } from './layout';

const escape = (value: string) =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/**
 * The configuration of a WinSW service wrapper, which runs the binary as a Windows service: it
 * starts `serve` with the same workspace, audit log and site policy as the systemd unit and
 * restarts it on failure. The site supplies the wrapper executable beside this file, named as
 * the service.
 */
export function windowsServiceXml(layout: InstallLayout, executable: string): string {
  const args = [
    'serve',
    '--workspace',
    `"${layout.workspace}"`,
    '--audit-log',
    `"${layout.audit}"`,
    '--site-policy',
    `"${layout.policy}"`,
  ].join(' ');
  return `<!-- Generated by \`app install\`. Do not edit; reinstall. -->
<service>
  <id>${escape(layout.service)}</id>
  <name>${escape(layout.service)}</name>
  <description>tortoise local host</description>
  <executable>${escape(executable)}</executable>
  <arguments>${escape(args)}</arguments>
  <onfailure action="restart" delay="5 sec" />
  <startmode>Automatic</startmode>
</service>
`;
}
