// Expo config plugin, run by `expo prebuild` with the options `mobile:prepare` lists for it:
// `{ application: { id, title }, settings: [{ key, description }] }`, every setting the composed
// plugins declare. Android needs the keys an MDM may set declared at build time
// (`res/xml/app_restrictions.xml`); iOS managed app configuration needs no declaration.
const { mkdirSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const escape = (text) =>
  String(text)
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

function restrictionsXml(settings) {
  const entries = settings.map(
    (setting) =>
      `  <restriction android:key="${escape(setting.key)}" android:title="${escape(setting.key)}" ` +
      `android:description="${escape(setting.description)}" android:restrictionType="string" />`,
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by @tortoise/managed-config at prebuild. Do not edit. -->',
    '<restrictions xmlns:android="http://schemas.android.com/apk/res/android">',
    ...entries,
    '</restrictions>',
    '',
  ].join('\n');
}

module.exports = function withManagedConfig(config, options = {}) {
  const settings = options.settings ?? [];
  config = withDangerousMod(config, [
    'android',
    async (config) => {
      const directory = join(config.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      mkdirSync(directory, { recursive: true });
      writeFileSync(join(directory, 'app_restrictions.xml'), restrictionsXml(settings));
      return config;
    },
  ]);
  return withAndroidManifest(config, (config) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    AndroidConfig.Manifest.addMetaDataItemToMainApplication(
      application,
      'android.content.APP_RESTRICTIONS',
      '@xml/app_restrictions',
      'resource',
    );
    return config;
  });
};

module.exports.restrictionsXml = restrictionsXml;
