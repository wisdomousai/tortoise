using System.Text;
using System.Text.Json;

namespace Tortoise.Driver;

/// <summary>
/// Generates a C# file from a contract file: a static class with <c>Digest</c> and
/// <c>Document</c>, and one record per action input, action result and event payload. Records bind
/// JSON names with <c>JsonPropertyName</c>, so <c>Driver.Action</c>
/// can hand a handler its typed input.
/// </summary>
public static class Stubgen
{
    public static string Generate(string contractFile, string @namespace, string? className = null)
    {
        var (document, digest) = ContractFile.Read(contractFile);
        var id = document.GetProperty("id").GetString()!;
        var version = document.GetProperty("version").GetString()!;
        var types = new Types();
        if (document.TryGetProperty("actions", out var actions))
            foreach (var action in actions.EnumerateObject())
            {
                types.Type(action.Value.GetProperty("input"), Name(action.Name, "input"));
                if (action.Value.TryGetProperty("result", out var result)) types.Type(result, Name(action.Name, "result"));
            }
        if (document.TryGetProperty("events", out var events))
            foreach (var item in events.EnumerateObject())
                if (item.Value.TryGetProperty("payload", out var payload)) types.Type(payload, Name(item.Name, "payload"));
        var holder = className ?? Name(id, "contract");
        var text = new StringBuilder();
        text.Append($$"""
            // <auto-generated/>
            // Generated from the {{id}} driver contract {{version}}. Do not edit; regenerate with Tortoise.Driver.Stubgen.
            #nullable enable
            using System.Collections.Generic;
            using System.Text.Json.Nodes;
            using System.Text.Json.Serialization;

            namespace {{@namespace}};

            public static class {{holder}}
            {
                public const string Digest = "{{digest}}";

                private const string Text = @"{{ContractFile.Canonical(document).Replace("\"", "\"\"")}}";

                /// <summary>A fresh copy of the contract document.</summary>
                public static JsonObject Document => (JsonObject)JsonNode.Parse(Text)!;
            }

            """);
        foreach (var record in types.Records) text.Append('\n').Append(record);
        return text.ToString();
    }

    /// <summary>PascalCase from the words of every part: <c>setpoint.set</c>, <c>input</c> → <c>SetpointSetInput</c>.</summary>
    public static string Name(params string[] parts)
    {
        var words = parts.SelectMany(part => part.Split(NonWord, StringSplitOptions.RemoveEmptyEntries));
        var name = string.Concat(words.Select(word => char.ToUpperInvariant(word[0]) + word[1..]));
        return name.Length == 0 || char.IsDigit(name[0]) ? "P" + name : name;
    }

    private static readonly char[] NonWord =
        Enumerable.Range(0, 128).Select(code => (char)code).Where(c => !char.IsAsciiLetterOrDigit(c)).ToArray();

    private sealed class Types
    {
        public List<string> Records { get; } = [];

        /// <summary>The C# type for a JSON Schema, declaring records for objects with properties.</summary>
        public string Type(JsonElement schema, string name)
        {
            if (schema.ValueKind != JsonValueKind.Object) return "JsonNode?";
            if (schema.TryGetProperty("enum", out var options))
                return Common(options.EnumerateArray().Select(Literal));
            if (schema.TryGetProperty("const", out var constant)) return Literal(constant);
            if (schema.TryGetProperty("anyOf", out _) || schema.TryGetProperty("oneOf", out _)) return "JsonNode?";
            if (!schema.TryGetProperty("type", out var kind)) return "JsonNode?";
            if (kind.ValueKind == JsonValueKind.Array)
            {
                var kinds = kind.EnumerateArray().Select(item => item.GetString()).ToList();
                var concrete = kinds.Where(item => item != "null").ToList();
                if (concrete.Count != 1) return "JsonNode?";
                return Nullable(Of(concrete[0]!, schema, name));
            }
            return Of(kind.GetString()!, schema, name);
        }

        private string Of(string kind, JsonElement schema, string name) => kind switch
        {
            "string" => "string",
            "integer" => "long",
            "number" => "double",
            "boolean" => "bool",
            "null" => "JsonNode?",
            "array" => $"IReadOnlyList<{(schema.TryGetProperty("items", out var items) ? Type(items, name + "Item") : "JsonNode?")}>",
            "object" when schema.TryGetProperty("properties", out var properties) => Record(schema, properties, name),
            "object" => "JsonObject",
            _ => "JsonNode?",
        };

        private static string Literal(JsonElement value) => value.ValueKind switch
        {
            JsonValueKind.String => "string",
            JsonValueKind.Number => value.TryGetInt64(out _) ? "long" : "double",
            JsonValueKind.True or JsonValueKind.False => "bool",
            _ => "JsonNode?",
        };

        private static string Common(IEnumerable<string> types)
        {
            var distinct = types.Distinct().ToList();
            return distinct.Count == 1 ? distinct[0] : "JsonNode?";
        }

        private static string Nullable(string type) => type.EndsWith('?') ? type : type + "?";

        private string Record(JsonElement schema, JsonElement properties, string name)
        {
            var required = schema.TryGetProperty("required", out var list)
                ? list.EnumerateArray().Select(item => item.GetString()).ToHashSet()
                : [];
            var parameters = new List<(string Text, bool Optional)>();
            var used = new HashSet<string> { name };
            foreach (var property in properties.EnumerateObject())
            {
                var member = Stubgen.Name(property.Name);
                while (!used.Add(member)) member += "Value";
                var type = Type(property.Value, name + Stubgen.Name(property.Name));
                var optional = !required.Contains(property.Name);
                var json = new StringBuilder();
                ContractFile.Quote(property.Name, json);
                parameters.Add(optional
                    ? ($"    [property: JsonPropertyName({json})] {Nullable(type)} {member} = null", true)
                    : ($"    [property: JsonPropertyName({json})] {type} {member}", false));
            }
            // Required parameters first, so the optional ones can default to null.
            var ordered = parameters.Where(item => !item.Optional).Concat(parameters.Where(item => item.Optional));
            var body = string.Join(",\n", ordered.Select(item => item.Text));
            Records.Add(parameters.Count == 0
                ? $"public sealed record {name}();\n"
                : $"public sealed record {name}(\n{body});\n");
            return name;
        }
    }
}
