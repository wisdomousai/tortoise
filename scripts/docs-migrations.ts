export function retiredTarget(page: string, fragment = ''): string {
  const entry = retiredDocs[page];
  if (!entry) throw new Error(`Unknown retired documentation page ${page}.`);
  const anchor = decodeURIComponent(fragment.replace(/^#/, ''));
  return entry.fragments[anchor] ?? entry.target;
}
