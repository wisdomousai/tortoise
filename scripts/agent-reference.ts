import type { Catalog, CatalogAgent } from '@tortoise/contracts';

const output = (agent: CatalogAgent) =>
  agent.output === 'direct'
    ? 'runs its commands itself'
    : 'submits its commands as approval requests for a person or allowed caller to approve';

const model = { local: 'on this host', remote: 'at a model provider', any: 'locally or remotely' };

function section(agent: CatalogAgent, tool: (id: string) => string): string {
  const scope = agent.resourceTypes?.length
    ? `- Scope: only the ${agent.resourceTypes.map((type) => `\`${type}\``).join(', ')} resources a run starts on\n`
    : '';
  return `## ${agent.id}\n\n${agent.title}. Declared by the \`${agent.module}\` module; ${output(agent)}; runs ${model[agent.model]}.\n\n${agent.instructions}\n\n- Operations: ${agent.operations.map((id) => `\`${id}\` (\`${tool(id)}\`)`).join(', ')}\n${scope}- Budgets per run: ${agent.budgets.turns} turns, ${agent.budgets.toolCalls} tool calls, ${agent.budgets.wallTimeMs / 1000} s\n`;
}

/** `agents.md`: every agent definition with its operations, scope and budgets. */
export function agentsMarkdown(catalog: Catalog): string {
  const tool = (id: string) => catalog.operations.find((operation) => operation.id === id)!.mcpName;
  return `# Application agents\n\nGenerated by \`bun run generate\`. A run under a definition acts as the person or grant that started it, narrowed to the listed operations; the application's policy authorizes every call.\n\n${
    catalog.agents.length
      ? catalog.agents.map((agent) => section(agent, tool)).join('\n')
      : 'This application defines no agents.\n'
  }`;
}

/** The operation reference line naming the agents that may call an operation. */
export function agentsOf(catalog: Catalog, operation: string): string {
  const agents = catalog.agents.filter((agent) => agent.operations.includes(operation));
  return agents.length
    ? `- Agents: ${agents.map((agent) => `\`${agent.id}\` (${agent.output})`).join(', ')}\n`
    : '';
}

/** The application skill's section listing agents, so an agent client knows its own role. */
export function agentSkillSection(catalog: Catalog): string {
  if (!catalog.agents.length) return '';
  return `## Agents\n\nWhen you run as one of these agents, call only its operations; the host refuses the rest. A requesting agent's commands are recorded as approval requests, not applied. Each agent's instructions are the \`app://agents/<id>\` MCP resource.\n\n${catalog.agents.map((agent) => `- \`${agent.id}\`: ${agent.title} (${agent.output}).`).join('\n')}\n\n`;
}
