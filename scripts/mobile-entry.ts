import { mkdir, writeFile } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve } from 'node:path';
import { readPluginSettings } from '@agent-native/host';
import { loadManifest } from '@agent-native/host/config';
import { readMobileTarget } from '@agent-native/host/mobile-target';
import { deploymentCatalog } from '@agent-native/kernel/components';
import { nativeOsConfig } from '@agent-native/shell/registrations';

const root = resolve(import.meta.dir, '..');

/**
 * Write the mobile app's entry for the application `app.config.json` names for mobile. Metro
 * bundles only what it can see, so the starter imports `virtual:agent-native/mobile-entry` and
 * Metro maps it to this file; the starter's source never names content. The entry imports the
 * application's server definition and its `screens-native`. Beside it, `native.json` lists the
 * Expo config plugins of the composed plugins with `{ application, settings }`, then the
 * application's own `expoPlugins` with their options, which
 * `app.config.ts` passes to `expo prebuild`, and `os`, the scheme, intent filters, associated
 * domains and document types its OS handlers need. The entry also carries the launcher settings
 * the identity implies: the application's URL scheme as the OS plugin's scheme setting, as the
 * desktop passes it, and verified link hosts from `AGENT_NATIVE_OS_LINK_HOSTS` in the build's
 * environment. A setting no composed plugin declares is left out. Fails when the application does not list `mobile`
 * among its targets; `defineManifest` has already refused plugins that cannot run there. Returns
 * the entry path and the application specifier.
 */
export async function writeMobileEntry({
  configPath = join(root, 'app.config.json'),
  directory = join(root, 'apps', 'mobile', 'generated'),
  env = process.env,
}: {
  configPath?: string;
  directory?: string;
  env?: Record<string, string | undefined>;
} = {}) {
  const config = readMobileTarget(configPath, env);
  const manifest = await loadManifest(config);
  if (!manifest.targets?.includes('mobile'))
    throw new Error(
      `${config.application} does not target mobile; add 'mobile' to its manifest's targets`,
    );
  const from = (entry: string) => {
    if (!isAbsolute(config.application)) return `${config.application}/${entry}`;
    const path = relative(directory, join(config.application, entry));
    return path.startsWith('.') ? path : `./${path}`;
  };
  const settings = readPluginSettings(manifest, {
    AGENT_NATIVE_OS_SCHEME: config.scheme,
    AGENT_NATIVE_OS_LINK_HOSTS: env.AGENT_NATIVE_OS_LINK_HOSTS,
  });
  const lines = [
    '// Generated by `bun run mobile:prepare` from app.config.json. Do not edit.',
    `import application from ${JSON.stringify(from('application'))};`,
    `import screens from ${JSON.stringify(from('screens-native'))};`,
    '',
    `const identity = ${JSON.stringify({ scheme: config.scheme })};`,
    `const settings = ${JSON.stringify(settings)};`,
    '',
    'export default { application, screens, identity, settings };',
  ];
  const linkHosts = (env.AGENT_NATIVE_OS_LINK_HOSTS ?? '')
    .split(',')
    .map((host) => host.trim())
    .filter(Boolean);
  const plugins = manifest.plugins ?? [];
  const declared = plugins
    .flatMap((plugin) => plugin.settings ?? [])
    .map(({ key, description }) => ({ key, description }));
  const native = {
    plugins: [
      ...plugins.flatMap((plugin) =>
        plugin.native?.expoPlugin
          ? [
              [
                plugin.native.expoPlugin,
                { application: { id: manifest.id, title: manifest.title }, settings: declared },
              ],
            ]
          : [],
      ),
      // Then the application's own, such as `expo-camera` with its permission text.
      ...(manifest.expoPlugins ?? []).map(({ plugin, options }) => [plugin, options ?? {}]),
    ],
    os: nativeOsConfig(
      deploymentCatalog(manifest).os,
      { appId: config.appId, scheme: config.scheme, displayName: config.displayName },
      { linkHosts },
    ),
  };
  await mkdir(directory, { recursive: true });
  const entry = join(directory, 'entry.ts');
  await writeFile(entry, lines.join('\n') + '\n');
  await writeFile(join(directory, 'native.json'), JSON.stringify(native, null, 2) + '\n');
  return { entry, application: config.application };
}

if (import.meta.main) {
  const { entry, application } = await writeMobileEntry();
  console.log(`Mobile entry for ${application}: ${relative(root, entry)}`);
}
